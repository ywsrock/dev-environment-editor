-- =============================================================================
-- options.lua - 基本設定
-- =============================================================================

local opt = vim.opt

-- -----------------------------------------------------------------------------
-- エンコーディング
-- -----------------------------------------------------------------------------
opt.encoding = "utf-8"
opt.fileencodings = { "utf-8", "sjis", "euc-jp", "cp932", "default", "latin1", "iso-2022-jp", "ucs-bom" }
opt.fileformats = { "unix", "dos", "mac" }

-- -----------------------------------------------------------------------------
-- 表示
-- -----------------------------------------------------------------------------
opt.number = true           -- 行番号表示
opt.cursorline = true       -- カーソル行をハイライト
opt.showmatch = true        -- 対応する括弧をハイライト
opt.showcmd = true          -- 入力中のコマンドを表示
opt.showmode = true         -- 現在のモードを表示
opt.laststatus = 2          -- 常にステータスラインを表示
opt.signcolumn = "yes"      -- サインカラムを常に表示
opt.ambiwidth = "double"    -- 曖昧な幅の文字を全角として扱う
vim.cmd("syntax on")

-- -----------------------------------------------------------------------------
-- 検索
-- -----------------------------------------------------------------------------
opt.hlsearch = true         -- 検索結果をハイライト
opt.incsearch = true        -- インクリメンタルサーチ
opt.ignorecase = true       -- 大文字小文字を無視
opt.smartcase = true        -- 大文字が含まれていたら区別

-- -----------------------------------------------------------------------------
-- インデント / タブ
-- -----------------------------------------------------------------------------
opt.autoindent = true       -- 自動インデント
opt.tabstop = 2             -- タブ幅
opt.shiftwidth = 2          -- インデント幅
opt.expandtab = true        -- タブをスペースに変換

-- -----------------------------------------------------------------------------
-- 編集
-- -----------------------------------------------------------------------------
opt.backspace = { "indent", "eol", "start" }  -- バックスペースで何でも消せるように
opt.clipboard = "unnamedplus"                  -- システムクリップボードを使用

-- -----------------------------------------------------------------------------
-- ウィンドウ / バッファ
-- -----------------------------------------------------------------------------
opt.splitright = true       -- 新しいウィンドウを右に開く
opt.autochdir = true        -- カレントディレクトリを自動的に変更

-- -----------------------------------------------------------------------------
-- 補完
-- -----------------------------------------------------------------------------
opt.wildmenu = true         -- コマンドライン補完
opt.wildmode = { "list", "full" }  -- 補完モード

-- -----------------------------------------------------------------------------
-- 折りたたみ
-- -----------------------------------------------------------------------------
opt.foldmethod = "indent"   -- インデントで折りたたみ
opt.foldnestmax = 10        -- 最大折りたたみ深度
opt.foldenable = false      -- 起動時は折りたたまない
opt.foldlevel = 2

-- -----------------------------------------------------------------------------
-- バックアップ / スワップ
-- -----------------------------------------------------------------------------
opt.backup = false
opt.writebackup = false

-- -----------------------------------------------------------------------------
-- パフォーマンス
-- -----------------------------------------------------------------------------
opt.updatetime = 300        -- CursorHold までの時間（ms）

-- -----------------------------------------------------------------------------
-- その他
-- -----------------------------------------------------------------------------
opt.belloff = "all"         -- ベルを無効化

-- -----------------------------------------------------------------------------
-- スペルチェック（VSCode以外）
-- -----------------------------------------------------------------------------
if not vim.g.vscode then
  opt.spell = true
  opt.spelllang = { "en_us", "cjk" }
  opt.complete:append("kspell")
end

-- -----------------------------------------------------------------------------
-- True Color サポート
-- -----------------------------------------------------------------------------
if vim.fn.has("termguicolors") == 1 then
  opt.termguicolors = true
end

-- -----------------------------------------------------------------------------
-- フォント設定（Neovide以外）
-- -----------------------------------------------------------------------------
if not vim.g.neovide then
  opt.guifontwide = "MS_Gothic:h9"
  opt.guifont = "Menlo Regular:h14"
end
